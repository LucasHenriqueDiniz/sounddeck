#!/usr/bin/env node
/**
 * Generates landing-page/packs-data.js from src/mocks/packs.ts — the same
 * SOUND_PACKS array the app itself renders in the Library view. This keeps
 * the landing page's pack showcase (ids, names, release years, cover
 * gradients/glyphs) from drifting out of sync with what's actually in the
 * app; only descriptions stay landing-page-owned, since translation is a
 * marketing-copy concern the app data doesn't carry.
 *
 * Run manually after editing src/mocks/packs.ts:
 *   npm run build:landing-packs
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { SOUND_PACKS } from "../src/mocks/packs.ts";

const SCRIPT_DIR = fileURLToPath(new URL(".", import.meta.url));
const OUT_FILE = join(SCRIPT_DIR, "..", "landing-page", "packs-data.js");

const packs = SOUND_PACKS.map((pack) => ({
  id: pack.id,
  name: pack.name,
  author: pack.author,
  origin: pack.origin,
  releaseYear: pack.releaseYear ?? null,
  cover: pack.cover,
}));

const banner =
  "// AUTO-GENERATED by scripts/build-landing-packs.mjs from src/mocks/packs.ts.\n" +
  "// Do not hand-edit — run `npm run build:landing-packs` after changing the pack list.\n";

writeFileSync(OUT_FILE, `${banner}window.SOUNDDECK_PACKS = ${JSON.stringify(packs, null, 2)};\n`);

console.log(`Wrote ${packs.length} packs to ${OUT_FILE}`);
